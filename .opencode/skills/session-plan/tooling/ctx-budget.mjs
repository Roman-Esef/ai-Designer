#!/usr/bin/env node
/* ctx-budget — смета контекстного окна на заход.
 *
 * Зачем: окно рабочей модели ~250 000 токенов на сессию, вход и выход вместе.
 * Заход «собрать крупный экран» в него не укладывается, и узнаётся это на
 * середине сборки, когда половина работы уже оплачена. Смета считается ДО
 * старта этапа и говорит одно из трёх: OK, ВНИМАНИЕ, РАЗБИТЬ.
 *
 * Половина смысла инструмента — в том, что большие файлы читает СКРИПТ, а не
 * агент: `_cheatsheet.md` (238 КБ) измеряется по блокам, не попадая в контекст
 * ни одним токеном.
 *
 * Паспорт этапов и коэффициенты — в stages.json рядом. Прозой состав этапа
 * нигде не пересказывается: его печатает `--stages` (копия прозой разъезжается
 * с файлом — урок Л43).
 *
 *   node ctx-budget.mjs --stages
 *   node ctx-budget.mjs --stage build --tz <путь> --cheat Table,Modal --out-lines 900
 *   node ctx-budget.mjs --stage review --screen Concepts/DealRegistry/DealRegistry.html --tz <путь>
 *   node ctx-budget.mjs --selftest
 *
 * Истина — строка ВЕРДИКТ, а не код выхода (ds-rules §8).
 */

import { readFileSync, existsSync, statSync, appendFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..', '..');
const STAGES_FILE = path.join(HERE, 'stages.json');
const CHEATSHEET = path.join(ROOT, 'DS-IBP', 'specs', '_cheatsheet.md');

const П = JSON.parse(readFileSync(STAGES_FILE, 'utf8'));
const К = П['коэффициенты'];

/* Вывод регулярно читают через `| head`/`| grep`: закрытый пайп — это norma,
   а не сбой инструмента. Без этого обработчика node роняет стек EPIPE поверх
   отчёта, и строка ВЕРДИКТ теряется среди трассы. */
process.stdout.on('error', (e) => { if (e && e.code === 'EPIPE') process.exit(0); throw e; });

const log = (s = '') => process.stdout.write(s + '\n');

/* ---------------- оценка токенов ----------------
   Кириллица дороже латиницы почти вдвое: у распространённых токенизаторов
   русское слово режется на 2–4 куска, английское часто остаётся одним.
   Поэтому два коэффициента, а не средний по больнице. */

const КИРИЛЛИЦА = /[Ѐ-ӿ]/gu;

function оценка(text) {
  const кир = (text.match(КИРИЛЛИЦА) || []).length;
  const проч = text.length - кир;
  return Math.round(кир / К['симв_на_токен_кириллица'] + проч / К['симв_на_токен_прочее']);
}

function файл(rel) {
  const abs = path.isAbsolute(rel) ? rel : path.resolve(ROOT, rel);
  if (!existsSync(abs)) return { есть: false, токенов: 0, байт: 0 };
  return { есть: true, токенов: оценка(readFileSync(abs, 'utf8')), байт: statSync(abs).size };
}

const сумма = (список) => список.reduce((s, rel) => s + файл(rel).токенов, 0);

/* ---------------- блоки чит-шита ----------------
   Чит-шит читает скрипт. Агент не платит за него ничего. */

function блокиЧитШита() {
  const карта = new Map();
  if (!existsSync(CHEATSHEET)) return карта;
  let имя = null;
  for (const line of readFileSync(CHEATSHEET, 'utf8').split(/\r?\n/)) {
    const m = /^## (.+)$/.exec(line);
    if (m) имя = m[1].trim();
    if (имя) карта.set(имя, (карта.get(имя) || '') + line + '\n');
  }
  return карта;
}

function найтиБлок(карта, запрос) {
  const q = запрос.trim().toLowerCase();
  for (const имя of карта.keys()) if (имя.toLowerCase() === q) return имя;
  for (const имя of карта.keys()) {
    const n = имя.toLowerCase();
    if (n.startsWith(q) && /^[\s(]/.test(имя.slice(запрос.length) || ' ')) return имя;
  }
  return null;
}

/* ---------------- аргументы ---------------- */

const argv = process.argv.slice(2);
const флаг = (n) => argv.includes(n);
const знач = (n, def = null) => {
  const i = argv.indexOf(n);
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : def;
};
const всеЗнач = (n) => {
  const out = [];
  argv.forEach((a, i) => { if (a === n && argv[i + 1] && !argv[i + 1].startsWith('--')) out.push(argv[i + 1]); });
  return out;
};

const ч = (n) => String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');

const ПОТОЛОК = Number(знач('--limit', П['пороги']['потолок']));
const РАБОЧИЙ = Math.round(ПОТОЛОК * (1 - П['пороги']['резерв_доля']));
const ВНИМАНИЕ = П['пороги']['внимание'];

const вердикт = (итого) => (итого <= ВНИМАНИЕ ? 'OK' : итого <= РАБОЧИЙ ? 'ВНИМАНИЕ' : 'РАЗБИТЬ');

/* ---------------- --stages ---------------- */

function паспорт() {
  log('== Паспорт этапов (источник: stages.json) ==');
  log('');
  log(`окно ${ч(ПОТОЛОК)} · рабочий потолок ${ч(РАБОЧИЙ)} · ВНИМАНИЕ с ${ч(ВНИМАНИЕ)}`);
  const пв = П['постоянный вход'];
  log(`постоянный вход в каждой сессии: ${пв.join(', ')} — ${ч(сумма(пв))}`);
  log('');
  for (const [имя, м] of Object.entries(П['маршруты'])) {
    log(`МАРШРУТ «${имя}» — ${м['когда']}`);
    log('  ' + м['этапы'].join(' → '));
    log('');
  }
  for (const [имя, э] of Object.entries(П['этапы'])) {
    const инстр = сумма(э['читает']);
    log(`${имя}  [${э['роль']}]  инструктаж ${ч(инстр)}`);
    log(`  делает: ${э['делает']}`);
    for (const rel of э['читает']) {
      const f = файл(rel);
      log(`    ${f.есть ? ч(f.токенов).padStart(7) : '  НЕТ  '}  ${rel}`);
    }
    log('');
  }
  log('Данные задачи (ТЗ, блоки чит-шита, собранный экран) в паспорт не входят —');
  log('они зависят от экрана и задаются флагами --tz / --cheat / --screen.');
}

/* ---------------- смета ---------------- */

/* `о` — те же аргументы объектом (ключи без `--`), плюс `тихо`. Через него
   смету вызывает селфтест: обратный тест обязан гонять ТУ ЖЕ модель, а не её
   вторую копию арифметикой — копия разойдётся при первой правке коэффициента
   и начнёт подтверждать сама себя. */
function смета(имяЭтапа, о = null) {
  const арг = (имя, def = null) => (о ? (о[имя] !== undefined ? о[имя] : def) : знач('--' + имя, def));
  const аргСписок = (имя) => (о ? о[имя] || [] : всеЗнач('--' + имя));
  const печать = о && о.тихо ? () => {} : log;

  const э = П['этапы'][имяЭтапа];
  if (!э) {
    печать(`ОШИБКА: этап «${имяЭтапа}» в паспорте не описан. Известные: ${Object.keys(П['этапы']).join(', ')}`);
    if (о) return null;
    process.exit(1);
  }

  const строки = [];
  const пусто = [];
  let итого = 0;
  const статья = (подпись, токенов) => { итого += токенов; строки.push([подпись, токенов]); };

  const пв = П['постоянный вход'];
  статья(`постоянный вход (${пв.length} файла)`, сумма(пв));

  const инстр = сумма(э['читает']);
  for (const rel of э['читает']) if (!файл(rel).есть) пусто.push(rel);
  статья(`инструктаж этапа (${э['читает'].length} файлов)`, инстр);

  for (const rel of [...аргСписок('tz'), ...аргСписок('read')]) {
    const f = файл(rel);
    if (!f.есть) { пусто.push(rel); continue; }
    статья(`данные: ${path.basename(rel)}`, f.токенов);
  }

  /* Данные числом, а не файлом — так задан оракул обратного теста: он обязан
     считаться одинаково и через год, когда исходного ТЗ в репозитории уже нет
     (14.09.2026 именно это и случилось с Projects/post/operations-did). */
  const данныеФикс = Number(арг('данные_фикс', 0));
  if (данныеФикс) статья('данные (задано числом)', данныеФикс);

  const cheatArg = арг('cheat');
  if (cheatArg) {
    const карта = блокиЧитШита();
    if (!карта.size) {
      печать('ОШИБКА: DS-IBP/specs/_cheatsheet.md не прочитан — блоки посчитать нечем.');
      if (о) return null;
      process.exit(1);
    }
    const имена = cheatArg.split(',').map((s) => s.trim()).filter(Boolean);
    let токенов = 0;
    const ненайдены = [];
    for (const зап of имена) {
      const найдено = найтиБлок(карта, зап);
      if (!найдено) { ненайдены.push(зап); continue; }
      токенов += оценка(карта.get(найдено));
    }
    статья(`блоки чит-шита (${имена.length - ненайдены.length} из ${имена.length})`, токенов);
    if (ненайдены.length) {
      строки.push([`  НЕ НАЙДЕНО в чит-шите: ${ненайдены.join(', ')}`, null]);
    }
  }

  let screenТокенов = 0;
  const screenArg = арг('screen');
  if (screenArg) {
    const f = файл(screenArg);
    if (!f.есть) пусто.push(screenArg);
    else { screenТокенов = f.токенов; статья(`экран целиком: ${path.basename(screenArg)}`, f.токенов); }
  }

  let экранТокенов = 0;
  const outLines = Number(арг('out-lines', 0));
  if (э['выход_html']) {
    if (!outLines) {
      строки.push(['  ВНИМАНИЕ: --out-lines не задан, запись экрана в смету не вошла', null]);
    } else {
      экранТокенов = Math.round(outLines * К['токенов_на_строку_html']);
      статья(`запись: ${ч(outLines)} строк HTML`, экранТокенов);
    }
  }
  if (э['выход_спека'] && экранТокенов) {
    статья(`запись: спека (${String(К['спека_доля_от_экрана']).replace('.', ',')} × экрана)`, Math.round(экранТокенов * К['спека_доля_от_экрана']));
  }
  if (э['выход_фикс']) статья('запись: отчёт этапа', э['выход_фикс']);

  /* Круги правок — поштучно, а не долей от сметы. Главный расход круга не в
     самой правке, а в том, читается ли экран целиком или 20–40 строк вокруг
     якоря. Плоская доля этого не видит и врёт в безопасную сторону. */
  let дельтаПеречитывания = 0;
  if (э['круги']) {
    const кругов = Number(арг('rounds', К['круги_по_умолчанию']));
    const режим = арг('reread', 'anchor');
    if (режим !== 'anchor' && режим !== 'full') {
      печать(`ОШИБКА: --reread принимает anchor или full, получено «${режим}»`);
      if (о) return null;
      process.exit(1);
    }
    const база = screenТокенов || экранТокенов;
    const доля = режим === 'full' ? К['перечитывание_доля_целиком'] : К['перечитывание_доля_якорь'];
    const инаяДоля = режим === 'full' ? К['перечитывание_доля_якорь'] : К['перечитывание_доля_целиком'];
    const круг = Math.round(база * доля) + К['правка_на_круг_токенов'];
    const инойКруг = Math.round(база * инаяДоля) + К['правка_на_круг_токенов'];
    статья(`круги правок: ${кругов} × ${режим === 'full' ? 'перечитывание экрана целиком' : 'правка по якорю'}`, круг * кругов);
    дельтаПеречитывания = (инойКруг - круг) * кругов;
  }

  печать(`== Смета этапа «${имяЭтапа}» [${э['роль']}] ==`);
  for (const [подпись, токенов] of строки) {
    if (токенов === null) печать(`  ${подпись}`);
    else печать(`  ${подпись.padEnd(46, ' ')}${ч(токенов).padStart(9)}`);
  }
  печать('  ' + '-'.repeat(55));
  печать(`  ${'ИТОГО'.padEnd(46, ' ')}${ч(итого).padStart(9)}   из ${ч(РАБОЧИЙ)} (окно ${ч(ПОТОЛОК)})`);

  if (дельтаПеречитывания) {
    const иначе = итого + дельтаПеречитывания;
    const знак = дельтаПеречитывания > 0 ? '+' : '−';
    const другой = арг('reread', 'anchor') === 'full' ? 'правка только по якорю' : 'перечитывание экрана целиком';
    печать(`  справочно: ${другой} — ${знак}${ч(Math.abs(дельтаПеречитывания))} → ${ч(иначе)} (${вердикт(иначе)})`);
  }

  if (пусто.length) {
    печать('');
    печать('  ФАЙЛЫ НЕ НАЙДЕНЫ (в смету не вошли, число занижено):');
    for (const rel of пусто) печать(`    ${rel}`);
  }

  const в = вердикт(итого);
  печать('');
  if (в === 'OK') печать(`ВЕРДИКТ: OK — запас ${ч(РАБОЧИЙ - итого)}`);
  else if (в === 'ВНИМАНИЕ') печать(`ВЕРДИКТ: ВНИМАНИЕ — ${ч(итого)} из ${ч(РАБОЧИЙ)}, запас ${ч(РАБОЧИЙ - итого)}. Один лишний круг правок съест его.`);
  else {
    печать(`ВЕРДИКТ: РАЗБИТЬ — смета ${ч(итого)} больше рабочего потолка ${ч(РАБОЧИЙ)}`);
    if (э['делится_на']) {
      печать(`  этап делится: ${э['делится_на'].join(' → ')}`);
      печать(`  считать каждый отдельно: --stage ${э['делится_на'][0]} --out-lines <строк своей части>`);
    } else {
      печать('  подэтапов в паспорте нет — сузить вход: меньше блоков чит-шита за раз,');
      печать('  ТЗ читать секцией, экран не перечитывать целиком (ds-rules §13).');
    }
  }

  return { итого, вердикт: в };
}

/* ---------------- --selftest ----------------
   Проверяются чистые функции с известным ответом и целостность паспорта.
   Замер коэффициента ломает проверку 1 намеренно: коэффициент не меняется
   мимоходом — только вместе с `селфтест.эталон_токенов`. */

function selftest() {
  const с = П['селфтест'];
  const провалы = [];
  log('== ctx-budget --selftest ==');

  const эталон = 'абв'.repeat(с['эталон_строка_кириллица'] / 3) + 'abcdefgh'.repeat(с['эталон_строка_прочее'] / 8);
  const получено = оценка(эталон);
  const ok1 = получено === с['эталон_токенов'];
  log(`  1. оценка эталонной строки: ${получено}, ожидалось ${с['эталон_токенов']} ${ok1 ? 'OK' : 'ПРОВАЛ'}`);
  if (!ok1) провалы.push('оценка токенов разошлась с эталоном — коэффициент изменён без правки селфтеста');

  const пары = [[100000, 'OK'], [160000, 'ВНИМАНИЕ'], [210000, 'РАЗБИТЬ']];
  const плохие = пары.filter(([n, ждём]) => вердикт(n) !== ждём);
  log(`  2. пороги: ${пары.map(([n, ж]) => ч(n) + '→' + вердикт(n)).join(', ')} ${плохие.length ? 'ПРОВАЛ' : 'OK'}`);
  if (плохие.length) провалы.push('пороги дают не тот вердикт');

  const всеФайлы = [...П['постоянный вход'], ...Object.values(П['этапы']).flatMap((э) => э['читает'])];
  const уник = [...new Set(всеФайлы)];
  const нет = уник.filter((rel) => !файл(rel).есть);
  log(`  3. файлы паспорта на месте: ${уник.length - нет.length} из ${уник.length} ${нет.length ? 'ПРОВАЛ' : 'OK'}`);
  for (const rel of нет) log(`       нет: ${rel}`);
  if (нет.length) провалы.push('паспорт ссылается на несуществующие файлы');

  const вМаршрутах = [...new Set(Object.values(П['маршруты']).flatMap((м) => м['этапы']))];
  const безОписания = вМаршрутах.filter((имя) => !П['этапы'][имя]);
  log(`  4. этапы маршрутов описаны: ${вМаршрутах.length - безОписания.length} из ${вМаршрутах.length} ${безОписания.length ? 'ПРОВАЛ' : 'OK'}`);
  for (const имя of безОписания) log(`       без описания: ${имя}`);
  if (безОписания.length) провалы.push('в маршруте есть этап без описания');

  const блоки = блокиЧитШита();
  const ok5 = блоки.size > 40;
  log(`  5. чит-шит разобран на блоки: ${блоки.size} ${ok5 ? 'OK' : 'ПРОВАЛ'}`);
  if (!ok5) провалы.push('чит-шит не разобрался — --cheat считал бы нули молча');

  /* Обратный тест: модель прогоняется на ЗАВЕДОМО провалившемся заходе. Без
     него смета проверяется на правдоподобие числа, а правдоподобное число —
     ровно то, что выдала первая редакция модели, промахнувшись на 70 000. */
  const от = П['обратный_тест'];
  if (от) {
    const r = смета(от['этап'], { ...от, тихо: true });
    const ok6 = r && r.вердикт === от['ждём'];
    log(`  6. обратный тест на известном провале (${от['этап']}, ${r ? ч(r.итого) : '—'}): ${r ? r.вердикт : 'ОШИБКА'}, ожидалось ${от['ждём']} ${ok6 ? 'OK' : 'ПРОВАЛ'}`);
    if (!ok6) провалы.push('модель не ловит заход, который заведомо не влез, — чинится модель, а не отчёт');
  }

  log('');
  if (провалы.length) {
    for (const p of провалы) log(`  ${p}`);
    log('ВЕРДИКТ: FAIL');
    process.exit(1);
  }
  log('ВЕРДИКТ: OK');
}

/* ---------------- калибровка ----------------

   Единственное, что нельзя проверить без реального захода: сходится ли смета
   с фактом. Поэтому это не проверка, а ДОЛГ — строка, которую печатает `state`
   и вылавливает `gate` при закрытии любого захода. Пока замеров нет, строка
   говорит об этом прямым текстом; правило, живущее только в памяти человека,
   этот репозиторий считает ненаписанным (Л37, Л68).

   Логика долга живёт ТОЛЬКО здесь. `state` и `gate` её показывают, а не
   повторяют: копия разошлась бы с оригиналом (Л43, находка Л-ВЛАДЕЛЕЦ). */

const CALIBRATION = path.join(HERE, 'calibration.jsonl');
const ПОРОГ_РАСХОЖДЕНИЯ = 25;

function замеры() {
  if (!existsSync(CALIBRATION)) return [];
  return readFileSync(CALIBRATION, 'utf8').split(/\r?\n/).filter((l) => l.trim())
    .map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
}

function строкаКалибровки() {
  const з = замеры();
  if (!з.length) {
    return 'калибровка сметы: замеров 0 — смета ни разу не сверена с фактом; коэффициенты в stages.json остаются оценкой (ctx-budget.mjs --calibrate --stage <этап> --fact <токенов>)';
  }
  const п = з[з.length - 1];
  const знак = п['расхождение_проц'] > 0 ? '+' : '';
  const хвост = Math.abs(п['расхождение_проц']) > ПОРОГ_РАСХОЖДЕНИЯ
    ? ` — расхождение больше ${ПОРОГ_РАСХОЖДЕНИЯ} %, коэффициенты в stages.json пора править`
    : '';
  return `калибровка сметы: замеров ${з.length}, последний ${п['дата']} (этап ${п['этап']}): смета ${ч(п['смета'])}, факт ${ч(п['факт'])}, расхождение ${знак}${п['расхождение_проц']} %${хвост}`;
}

function калибровать() {
  const этап = знач('--stage');
  const факт = Number(знач('--fact', знач('--факт', 0)));
  if (!этап || !факт) {
    log('ОШИБКА: нужны --stage <этап> и --fact <токенов> (сколько заход съел на самом деле).');
    log('Остальные аргументы — те же, что у сметы: --tz, --cheat, --out-lines, --rounds, --reread.');
    process.exit(1);
  }
  /* Смета печатается целиком: сверка без показанных слагаемых бесполезна —
     расхождение надо на что-то отнести. Аргументы берутся из командной строки,
     те же, что при планировании этапа. */
  const r = смета(этап, null);
  if (!r) process.exit(1);

  const д = new Date();
  const дата = `${String(д.getDate()).padStart(2, '0')}.${String(д.getMonth() + 1).padStart(2, '0')}.${д.getFullYear()}`;
  const запись = {
    дата,
    t: д.toISOString(),
    этап,
    смета: r.итого,
    факт,
    расхождение_проц: Math.round(((факт - r.итого) / r.итого) * 100),
    комментарий: знач('--note', знач('--комментарий', '')) || undefined,
  };
  appendFileSync(CALIBRATION, JSON.stringify(запись) + '\n', 'utf8');

  log(`Записано в ${path.relative(ROOT, CALIBRATION).split(path.sep).join('/')}:`);
  log(`  этап ${этап} · смета ${ч(r.итого)} · факт ${ч(факт)} · расхождение ${запись['расхождение_проц'] > 0 ? '+' : ''}${запись['расхождение_проц']} %`);
  log('');
  log(строкаКалибровки());
}

